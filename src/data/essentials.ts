/** Embassy in another country that also covers this one. */
function covering(key: string, koCountry: string, enCountry: string): Embassy {
  const base = EMB[key]
  return {
    ...base,
    note: T(
      `${koCountry}에는 한국 대사관이 없어 ${base.name.ko}이 맡습니다.`,
      `There is no Korean embassy in ${enCountry}; it is covered by the ${base.name.en}.`,
    ),
  }
}

