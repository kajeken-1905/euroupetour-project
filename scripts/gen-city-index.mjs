// Writes src/data/cityIndex.ts — the few fields per city that lists, the map and the checklist need,
// so those screens do not have to load every city's sights (src/data/cities.ts).
// Runs before `npm run dev` and `npm run build`; needs Node 22.6+ (type stripping).
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { cities } from '../src/data/cities.ts'

const rows = cities.map((c) => {
  const brief = {
    id: c.id,
    countryId: c.countryId,
    name: c.name,
    nativeName: c.nativeName,
    signatureImage: c.signatureImage,
    cardTagline: c.cardTagline ?? c.highlights[0]?.name ?? { ko: '', en: '' },
    ...(c.lat === undefined ? {} : { lat: c.lat }),
    ...(c.lng === undefined ? {} : { lng: c.lng }),
  }
  return `  ${JSON.stringify(brief)},\n`
})

writeFileSync(
  fileURLToPath(new URL('../src/data/cityIndex.ts', import.meta.url)),
  `// Generated by scripts/gen-city-index.mjs from cities.ts. Do not edit by hand.
import type { CityBrief } from '../types'

export const cityIndex: CityBrief[] = [
${rows.join('')}]

export function getCityBrief(id: string) {
  return cityIndex.find((c) => c.id === id)
}

export function getCityBriefsByCountry(countryId: string) {
  return cityIndex.filter((c) => c.countryId === countryId)
}
`,
)
console.log(`cityIndex.ts: ${rows.length} cities`)
